#!/usr/bin/env bash
# Runs the Noctalia plugin's Luau tests against its sources, unmodified.
#
# The Luau CLI has no file I/O, so the plugin's .luau sources, plugin.toml,
# translations/en.json, the robot's frames and the test fixtures are embedded into tests/_generated/sources.luau first;
# tests/support/loader.luau then loads them with a fake `noctalia` host and
# Noctalia's require("./x.luau") semantics. The CLI is fetched once, checked
# against its SHA-256, into target/.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
plugin="${root}/noctalia/niri-computer-use"
version="0.742"
sha256="152058b98c60ff1f5b5ec9bca0b8eb37793cae161dd3a05608cc3d8738ba1a4d"
tools="${root}/target/luau-${version}"

if [[ ! -x "${tools}/luau" ]]; then
	mkdir -p "${tools}"
	curl -fsSL --max-time 120 -o "${tools}/luau.zip" \
		"https://github.com/luau-lang/luau/releases/download/${version}/luau-ubuntu.zip"
	echo "${sha256}  ${tools}/luau.zip" | sha256sum --check --quiet
	unzip -oq "${tools}/luau.zip" -d "${tools}"
	rm "${tools}/luau.zip"
fi

python3 - "${plugin}" <<'PY'
import pathlib, sys
root = pathlib.Path(sys.argv[1])
files = [p for p in root.rglob("*.luau") if p.relative_to(root).parts[0] != "tests"]
files += [root / "translations/en.json", root / "plugin.toml"]
files += sorted(root.glob("robot/*.svg")) + sorted(root.glob("tests/fixtures/*.jsonl"))

def quote(text):
    level = 0
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"

out = ["-- Generated by scripts/test-plugin.sh. Do not edit.", "return {"]
for path in sorted(files):
    out.append(f'  ["{path.relative_to(root).as_posix()}"] = {quote(path.read_text())},')
out.append("}")
generated = root / "tests/_generated"
generated.mkdir(exist_ok=True)
(generated / "sources.luau").write_text("\n".join(out) + "\n")
PY

cd "${plugin}"
exec timeout 60 "${tools}/luau" tests/run.luau
